/**
 * Google Search Console helpers shared by the `gsc` Edge Function (Deno) and its unit tests (Node).
 * Pure functions plus Web Crypto only: no network, no Deno APIs.
 */

export const GSC_SCOPES = ['https://www.googleapis.com/auth/webmasters.readonly', 'openid', 'email'] as const
export const GOOGLE_AUTH_URL = 'https://accounts.google.com/o/oauth2/v2/auth'
export const GOOGLE_TOKEN_URL = 'https://oauth2.googleapis.com/token'
export const GOOGLE_REVOKE_URL = 'https://oauth2.googleapis.com/revoke'
export const GSC_API = 'https://www.googleapis.com/webmasters/v3'

/** Search Console data is usually complete about 3 days after the fact. */
export const GSC_DATA_DELAY_DAYS = 3
export const GSC_PERIODS = [7, 28, 90] as const
export type GscPeriod = (typeof GSC_PERIODS)[number]
/** Rows requested per breakdown (queries, pages). */
export const GSC_ROW_LIMIT = 1000

export function isGscPeriod(value: unknown): value is GscPeriod {
  return typeof value === 'number' && (GSC_PERIODS as readonly number[]).includes(value)
}

// ---- OAuth ----------------------------------------------------------------------------------

/** Redirect URIs must match the allow-list exactly (scheme, host, port and path). */
export function isAllowedRedirect(uri: unknown, allowed: readonly string[]): uri is string {
  return typeof uri === 'string' && uri.length <= 500 && allowed.includes(uri)
}

export function parseAllowedRedirects(value: string | undefined): string[] {
  return (value ?? '')
    .split(',')
    .map((item) => item.trim())
    .filter((item) => /^https?:\/\/[^\s]+$/.test(item))
}

/** `state` is an opaque anti-forgery value generated by the browser. */
export function isValidState(state: unknown): state is string {
  return typeof state === 'string' && /^[A-Za-z0-9_-]{16,128}$/.test(state)
}

export function buildAuthUrl(clientId: string, redirectUri: string, state: string): string {
  const params = new URLSearchParams({
    client_id: clientId,
    redirect_uri: redirectUri,
    response_type: 'code',
    scope: GSC_SCOPES.join(' '),
    access_type: 'offline',
    prompt: 'consent',
    include_granted_scopes: 'true',
    state,
  })
  return `${GOOGLE_AUTH_URL}?${params.toString()}`
}

function base64UrlDecode(value: string): string {
  const padded = value.replace(/-/g, '+').replace(/_/g, '/').padEnd(Math.ceil(value.length / 4) * 4, '=')
  const binary = atob(padded)
  const bytes = Uint8Array.from(binary, (char) => char.charCodeAt(0))
  return new TextDecoder().decode(bytes)
}

/**
 * Reads the email claim from an ID token received directly from Google's token endpoint over TLS
 * (so the signature does not need verifying here). Returns null when absent or malformed.
 */
export function emailFromIdToken(idToken: unknown): string | null {
  if (typeof idToken !== 'string') return null
  const payload = idToken.split('.')[1]
  if (!payload) return null
  try {
    const claims = JSON.parse(base64UrlDecode(payload)) as { email?: unknown }
    return typeof claims.email === 'string' && claims.email.length <= 320 ? claims.email : null
  } catch {
    return null
  }
}

// ---- Token encryption (AES-GCM, key derived from a server secret) ---------------------------

async function deriveKey(secret: string): Promise<CryptoKey> {
  const material = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(`gsc-token-key:${secret}`))
  return crypto.subtle.importKey('raw', material, 'AES-GCM', false, ['encrypt', 'decrypt'])
}

function toBase64(bytes: Uint8Array): string {
  let binary = ''
  for (const byte of bytes) binary += String.fromCharCode(byte)
  return btoa(binary)
}

function fromBase64(value: string) {
  const binary = atob(value)
  // Backed by a plain ArrayBuffer, as Web Crypto requires.
  const bytes = new Uint8Array(new ArrayBuffer(binary.length))
  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index)
  return bytes
}

/** Encrypts a token for storage: "v1.<iv>.<ciphertext>" (base64). */
export async function encryptToken(plain: string, secret: string): Promise<string> {
  const iv = crypto.getRandomValues(new Uint8Array(12))
  const key = await deriveKey(secret)
  const cipher = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(plain)))
  return `v1.${toBase64(iv)}.${toBase64(cipher)}`
}

export async function decryptToken(stored: string, secret: string): Promise<string> {
  const [version, iv, cipher] = stored.split('.')
  if (version !== 'v1' || !iv || !cipher) throw new Error('Unsupported token format')
  const key = await deriveKey(secret)
  const plain = await crypto.subtle.decrypt({ name: 'AES-GCM', iv: fromBase64(iv) }, key, fromBase64(cipher))
  return new TextDecoder().decode(plain)
}

// ---- Properties and dates -------------------------------------------------------------------

/** "sc-domain:example.com" or a URL-prefix property such as "https://www.example.com/". */
export function isValidSiteUrl(value: unknown): value is string {
  if (typeof value !== 'string' || value.length > 300) return false
  if (value.startsWith('sc-domain:')) return /^sc-domain:[a-z0-9.-]+\.[a-z]{2,}$/i.test(value)
  return /^https?:\/\/[^\s/]+\/[^\s]*$/i.test(value)
}

function isoDate(date: Date): string {
  return date.toISOString().slice(0, 10)
}

function addDays(date: Date, days: number): Date {
  const copy = new Date(date.getTime())
  copy.setUTCDate(copy.getUTCDate() + days)
  return copy
}

export type DateRange = { startDate: string; endDate: string }

/** The last `days` days of complete data, and the same length of time just before it. */
export function periodRanges(today: Date, days: GscPeriod): { current: DateRange; previous: DateRange } {
  const end = addDays(today, -GSC_DATA_DELAY_DAYS)
  const start = addDays(end, -(days - 1))
  const prevEnd = addDays(start, -1)
  const prevStart = addDays(prevEnd, -(days - 1))
  return {
    current: { startDate: isoDate(start), endDate: isoDate(end) },
    previous: { startDate: isoDate(prevStart), endDate: isoDate(prevEnd) },
  }
}

// ---- Search analytics rows ------------------------------------------------------------------

export type GscRow = { key: string; clicks: number; impressions: number; ctr: number; position: number }
export type GscTotals = { clicks: number; impressions: number; ctr: number; position: number }

function finite(value: unknown): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : 0
}

/** Turns API rows ({ keys: [..], clicks, ... }) into flat rows keyed by the first dimension. */
export function normalizeRows(body: unknown): GscRow[] {
  const rows = typeof body === 'object' && body !== null ? (body as { rows?: unknown }).rows : undefined
  if (!Array.isArray(rows)) return []
  const out: GscRow[] = []
  for (const row of rows) {
    if (typeof row !== 'object' || row === null) continue
    const record = row as Record<string, unknown>
    const keys = Array.isArray(record.keys) ? record.keys : []
    const key = typeof keys[0] === 'string' ? keys[0].slice(0, 2048) : ''
    out.push({
      key,
      clicks: finite(record.clicks),
      impressions: finite(record.impressions),
      ctr: finite(record.ctr),
      position: finite(record.position),
    })
  }
  return out
}

/** Totals come back as a single row when no dimension is requested. */
export function normalizeTotals(body: unknown): GscTotals {
  const row = normalizeRows(body)[0]
  return row
    ? { clicks: row.clicks, impressions: row.impressions, ctr: row.ctr, position: row.position }
    : { clicks: 0, impressions: 0, ctr: 0, position: 0 }
}
